// Writes src/lib/icons.ts from GitHub's Octicons (@primer/octicons, MIT):
//   node scripts/icons.mjs
// Octicons are drawn on a 16px (and, for some, 12px) pixel grid, so at
// 100% scaling every edge lands on a pixel: Parzi uses them at 16px, and
// at 12px only where Octicons has a 12px drawing (else the 16px one scaled).
import { writeFile } from "node:fs/promises";
import octicons from "@primer/octicons";

// Parzi's name -> Octicon.
const MAP = {
  menu: "three-bars",
  home: "home",
  plus: "plus",
  close: "x",
  search: "search",
  settings: "gear",
  globe: "globe",
  chat: "comment",
  more: "kebab-horizontal",
  pencil: "pencil",
  fork: "repo-forked",
  copy: "copy",
  trash: "trash",
  arrowDown: "arrow-down",
  arrowUp: "arrow-up",
  arrowLeft: "arrow-left",
  arrowRight: "arrow-right",
  reload: "sync",
  pin: "pin",
  brain: "book",
  chevDown: "chevron-down",
  chevRight: "chevron-right",
  check: "check",
  lock: "lock",
  unlock: "unlock",
  spark: "sparkle",
  folder: "file-directory",
  project: "stack",
  shield: "shield",
  key: "key",
  clock: "clock",
  bot: "dependabot",
  file: "file",
  image: "image",
  branch: "git-branch",
  panel: "split-view",
  server: "server",
  alert: "alert",
  download: "download",
  external: "link-external",
  browser: "browser",
  tasks: "tasklist",
  play: "play",
  blocked: "blocked",
};

const out = [];
for (const [name, octicon] of Object.entries(MAP)) {
  const icon = octicons[octicon];
  if (!icon?.heights[16]) throw new Error(`no 16px octicon "${octicon}" for ${name}`);
  const sizes = [12, 16].filter((h) => icon.heights[h]);
  const body = sizes.map((h) => `${h}: ${JSON.stringify(icon.heights[h].path)}`).join(", ");
  out.push(`  ${name}: { ${body} },`);
}

const { version } = (await import("@primer/octicons/package.json", { with: { type: "json" } })).default;
await writeFile(
  new URL("../src/lib/icons.ts", import.meta.url),
  `// Generated by scripts/icons.mjs from @primer/octicons ${version} (MIT). Don't edit by hand.
// Each icon's SVG body at the pixel grids Octicons draws it on.
export const ICONS: Record<string, { 12?: string; 16: string }> = {
${out.join("\n")}
};

export type IconName =
${Object.keys(MAP).map((n) => `  | "${n}"`).join("\n")};
`,
);
console.log(`icons.ts: ${out.length} icons`);
