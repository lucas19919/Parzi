const dir = new URL("../node_modules/lucide-static/", import.meta.url);
const out = [];
for (const [name, lucide] of Object.entries(MAP)) {
  const svg = await readFile(new URL(`icons/${lucide}.svg`, dir), "utf8");
  const body = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg)?.[1];
  if (!body) throw new Error(`no lucide icon "${lucide}" for ${name}`);
  const shapes = body.trim().split(/\s*\n\s*/).join("");
  out.push(`  ${name}: ${JSON.stringify(shapes)},`);
}

const { version } = JSON.parse(await readFile(new URL("package.json", dir), "utf8"));
await writeFile(
  new URL("../src/lib/icons.ts", import.meta.url),
  `// Generated by scripts/icons.mjs from lucide-static ${version} (ISC). Don't edit by hand.
// Each icon's SVG shapes on Lucide's 24px grid. Icon.svelte draws them in strokes.
export const ICONS: Record<string, string> = {
${out.join("\n")}
};

export type IconName =
${Object.keys(MAP).map((n) => `  | "${n}"`).join("\n")};
`,
);
console.log(`icons.ts: ${out.length} icons`);
